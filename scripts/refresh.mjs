await update('README.md', readme);
let shell = await fs.readFile(join(root, 'scripts/bootstrap.sh'), 'utf8');
shell = shell.replace(/^MINIMUM_MACOS_MAJOR=.*$/m, 'MINIMUM_MACOS_MAJOR=' + Number(config.desktop.minimumMacOS.split('.')[0]));
